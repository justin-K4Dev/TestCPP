	// Using example
	namespace first
	{
		int x = 5;
		int y = 10;
	}

	namespace second
	{
		double x = 3.1416;
		double y = 2.7183;
	}

	void using_keyword()
	{
		/*
			📚 using 키워드

			using은 어떤 이름을 현재 범위로 가져와서
			매번 namespace::name 형태로 쓰지 않아도 되게 해주는 기능이다.

			형태는 크게 두 가지가 있다.

				1) using 선언
					using first::x;

				2) using namespace 지시문
					using namespace first;


			=======================================================================================
			1. using 선언
			=======================================================================================

			특정 이름 하나만 현재 범위로 가져온다.

			예:
				using first::x;
				using second::y;

			그러면 현재 블록 안에서는
				x -> first::x
				y -> second::y
			처럼 쓸 수 있다.


			=======================================================================================
			2. using namespace
			=======================================================================================

			네임스페이스 전체를 현재 범위에서 검색 가능하게 만든다.

			예:
				using namespace first;

			그러면 현재 블록 안에서는
			first 안의 이름들을 qualification 없이 바로 사용할 수 있다.


			=======================================================================================
			3. 주의사항
			=======================================================================================

			using namespace를 너무 넓은 범위에서 쓰면
			이름 충돌이 커질 수 있다.

			특히 헤더 파일이나 큰 프로젝트 전역에서는
			조심해서 써야 한다.

			그래서 실무에서는 종종

				using std::cout;
				using std::string;

			처럼 필요한 이름만 가져오거나,
			그냥 std::cout 처럼 명시적으로 쓰는 스타일을 선호한다.


			=======================================================================================
			4. 핵심 요약
			=======================================================================================

				- using name은 특정 이름 하나를 현재 범위에 도입한다.
				- using namespace는 네임스페이스 전체를 현재 범위에 도입한다.
				- 편리하지만 이름 충돌을 조심해야 한다.
		*/


		//=========================================================================================
		// [테스트 예제 1] using 선언
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] using 선언" << std::endl;
			std::cout << "==================================================" << std::endl;

			using first::x;
			using second::y;

			std::cout << x << '\n';
			std::cout << y << '\n';
			std::cout << first::y << '\n';
			std::cout << second::x << '\n';
			std::cout << std::endl;

			/*
				예상 출력:
					5
					2.7183
					10
					3.1416
			*/
		}


		//=========================================================================================
		// [테스트 예제 2] using namespace
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] using namespace" << std::endl;
			std::cout << "==================================================" << std::endl;

			using namespace first;

			std::cout << x << '\n';
			std::cout << y << '\n';
			std::cout << second::x << '\n';
			std::cout << second::y << '\n';
			std::cout << std::endl;

			/*
				예상 출력:
					5
					10
					3.1416
					2.7183
			*/
		}


		//=========================================================================================
		// [테스트 예제 3] 블록마다 using 범위가 다름
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 3] 블록마다 using 범위가 다름" << std::endl;
			std::cout << "==================================================" << std::endl;

			{
				using namespace first;
				std::cout << x << '\n';
			}
			{
				using namespace second;
				std::cout << x << '\n';
			}

			std::cout << std::endl;

			/*
				예상 출력:
					5
					3.1416
			*/
		}

		system("pause");
	}

