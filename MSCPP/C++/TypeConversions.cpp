	void keyword_explicit()
	{
		/*
			📚 explicit 키워드

			C++은 함수 호출이나 초기화에서
			각 인자마다 한 번의 암시적 변환을 허용한다.

			이것은 편리할 수 있지만,
			클래스에서는 원치 않는 자동 변환을 허용할 수도 있다.

			예:
				B(const A&)

			가 존재하면
				A 객체를 B로 자동 변환할 수 있다.

			즉:
				fn(B arg);
				A foo;
				fn(foo);

			도 허용될 수 있다.

			하지만 이것이 항상 의도한 동작은 아니다.
			이럴 때 explicit 를 사용해 암시적 변환을 막는다.


			=======================================================================================
			1. explicit 생성자
			=======================================================================================

			예:
				explicit B(const A& x) {}

			이렇게 하면
				B bar = foo;
			같은 암시적 초기화는 금지되고,

				B bar(foo);

			같은 명시적 생성만 허용된다.


			=======================================================================================
			2. 왜 필요한가?
			=======================================================================================

			explicit 는
			"이 변환은 자동으로 일어나면 안 된다"
			는 의도를 코드에 명확히 나타낸다.

			즉, 실수로 함수 호출에서 변환이 일어나거나
			예상치 못한 임시 객체 생성이 일어나는 것을 막을 수 있다.


			=======================================================================================
			3. 핵심 요약
			=======================================================================================

				- explicit 는 암시적 변환을 막는다.
				- 단일 인자 생성자에 특히 중요하다.
				- 원치 않는 자동 변환을 줄여준다.
		*/


		//=========================================================================================
		// [테스트 예제 1] explicit 생성자
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] explicit 생성자" << std::endl;
			std::cout << "==================================================" << std::endl;

			class A
			{
			};

			class B
			{
			public:
				explicit B(const A&)
				{
					std::cout << "explicit A -> B 생성자 호출" << std::endl;
				}

				B& operator=(const A&)
				{
					std::cout << "A -> B 대입 연산자 호출" << std::endl;
					return *this;
				}

				operator A()
				{
					std::cout << "B -> A 변환 연산자 호출" << std::endl;
					return A();
				}
			};

			class C
			{
			public:
				static void fn(B)
				{
					std::cout << "C::fn(B) 호출" << std::endl;
				}
			};

			A foo;
			B bar(foo);   // 명시적 생성 허용
			bar = foo;    // 대입 허용
			foo = bar;    // 변환 연산자 허용

			// C::fn(foo); // explicit 때문에 암시적 변환 금지
			C::fn(bar);

			std::cout << std::endl;
		}

		system("pause");
	}

