	void statements_n_flow_control()
	{
		/*
			📚 문장과 흐름 제어 (Statements and flow control)

			C++ 프로그램은 여러 개의 문장(statement)으로 구성된다.

			예:
				int x = 10;
				x = x + 1;
				std::cout << x;

			이 각각이 하나의 문장이다.

			단순 문장(simple statement)은 보통 세미콜론(;)으로 끝난다.
			그리고 기본적으로 프로그램은
			위에서 아래로, 앞에서 뒤로
			문장을 순서대로 실행한다.

			즉, 특별한 제어가 없다면
			프로그램은 선형(linear)으로 흘러간다.


			=======================================================================================
			1. 그런데 프로그램은 항상 직선처럼만 흐르지 않는다
			=======================================================================================

			실제 프로그램은 다음이 필요하다.

				- 조건에 따라 다른 코드를 실행
				- 같은 코드를 여러 번 반복
				- 중간에 반복을 멈춤
				- 특정 위치로 흐름을 바꿈

			이런 동작을 위해 C++은
			흐름 제어문(flow control statements)을 제공한다.


			=======================================================================================
			2. 대표적인 흐름 제어문
			=======================================================================================

				선택문(selection)
					if, else, switch

				반복문(iteration)
					while, do-while, for

				점프문(jump)
					break, continue, goto, return

			즉, 흐름 제어문은
			"언제 무엇을 실행할 것인가"
			를 결정하는 문법이다.


			=======================================================================================
			3. 단일 문장과 복합 문장
			=======================================================================================

			흐름 제어문 문법에서 statement 자리에 들어가는 것은
			단일 문장일 수도 있고,
			복합 문장(compound statement)일 수도 있다.

			복합 문장은 중괄호로 묶인 문장 블록이다.

			예:
				{
					statement1;
					statement2;
					statement3;
				}

			이 블록 전체가 하나의 문장처럼 취급된다.

			그래서 if, while, for 등의 본문에
			여러 문장을 넣고 싶다면
			중괄호를 사용해야 한다.


			=======================================================================================
			4. 핵심 요약
			=======================================================================================

				- C++ 프로그램은 문장들의 집합이다.
				- 기본 실행 흐름은 위에서 아래로이다.
				- 흐름 제어문은 조건/반복/점프를 가능하게 한다.
				- 여러 문장을 하나처럼 다루려면 복합 문장 { } 를 쓴다.
		*/


		//=========================================================================================
		// [테스트 예제 1] 단순 문장과 복합 문장 설명
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 단순 문장과 복합 문장 설명" << std::endl;
			std::cout << "==================================================" << std::endl;

			int x = 1; // 단순 문장
			x = x + 1; // 단순 문장

			{
				int y = 10;
				int z = 20;
				std::cout << "복합 문장 내부: y=" << y << ", z=" << z << std::endl;
			}

			std::cout << "x=" << x << std::endl;
			std::cout << std::endl;
		}

		system("pause");
	}

