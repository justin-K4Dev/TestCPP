	void iteration_statements()
	{
		/*
			📚 반복문 (Iteration statements)

			반복문은 어떤 문장이나 블록을
			여러 번 반복 실행하는 제어문이다.

			C++의 대표 반복문은 다음 3가지이다.

				- while
				- do-while
				- for

			각 반복문은 비슷한 목적을 가지지만
			조건 검사 시점과 사용 목적이 조금씩 다르다.


			=======================================================================================
			1. while 문
			=======================================================================================

			형태:
				while (condition)
					statement;

			의미:
				- 먼저 조건 검사
				- 참이면 실행
				- 다시 조건 검사
				- 거짓이면 종료

			즉, 조건이 처음부터 거짓이면 한 번도 실행되지 않을 수 있다.


			=======================================================================================
			2. do-while 문
			=======================================================================================

			형태:
				do
					statement;
				while (condition);

			의미:
				- 먼저 본문 실행
				- 그 다음 조건 검사
				- 참이면 반복

			즉, 조건과 관계없이 최소 1번은 실행된다.


			=======================================================================================
			3. for 문
			=======================================================================================

			형태:
				for (initialization; condition; increase)
					statement;

			의미:
				1) 초기화
				2) 조건 검사
				3) 본문 실행
				4) 증가식 실행
				5) 다시 조건 검사

			카운터 기반 반복에 특히 적합하다.


			=======================================================================================
			4. 핵심 요약
			=======================================================================================

				- while     : 조건 먼저 검사
				- do-while  : 본문 먼저 실행, 최소 1회 실행
				- for       : 초기화/조건/증가를 한 줄에 표현
		*/


		//=========================================================================================
		// [테스트 예제 1] while 카운트다운
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] while 카운트다운" << std::endl;
			std::cout << "==================================================" << std::endl;

			int n = 10;

			while (n > 0)
			{
				std::cout << n << ", ";
				--n;
			}

			std::cout << "liftoff!" << std::endl;
			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 2] do-while 최소 1회 실행
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] do-while 최소 1회 실행" << std::endl;
			std::cout << "==================================================" << std::endl;

			int n = 0;

			do
			{
				std::cout << "이 문장은 조건이 거짓이어도 한 번은 실행된다. n=" << n << std::endl;
			} while (n > 0);

			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 3] for 카운트다운
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 3] for 카운트다운" << std::endl;
			std::cout << "==================================================" << std::endl;

			for (int n = 10; n > 0; --n)
			{
				std::cout << n << ", ";
			}

			std::cout << "liftoff!" << std::endl;
			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 4] for 에서 여러 표현식
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 4] for 에서 여러 표현식" << std::endl;
			std::cout << "==================================================" << std::endl;

			for (int n = 0, i = 10; n <= i; ++n, --i)
			{
				std::cout << "n=" << n << ", i=" << i << std::endl;
			}

			std::cout << std::endl;
		}

		system("pause");
	}

