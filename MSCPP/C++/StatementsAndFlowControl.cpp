	void jump_statements()
	{
		/*
			📚 점프문 (Jump statements)

			점프문은 프로그램의 현재 실행 흐름을
			다른 위치로 이동시키는 문장이다.

			대표적으로:
				- break
				- continue
				- goto

			가 있다.

			이들은 반복문이나 switch 안에서
			흐름을 빠르게 바꾸는 데 사용된다.


			=======================================================================================
			1. break
			=======================================================================================

			break 는 가장 가까운 반복문 또는 switch 문을 즉시 종료한다.

			즉, 조건이 아직 남아 있어도
			강제로 빠져나온다.


			=======================================================================================
			2. continue
			=======================================================================================

			continue 는 현재 반복의 남은 부분을 건너뛰고
			다음 반복으로 넘어간다.

			즉, 반복문 전체를 끝내는 것이 아니라
			이번 회차만 스킵한다.


			=======================================================================================
			3. goto
			=======================================================================================

			goto 는 레이블(label)로 무조건 점프한다.

			예:
				goto mylabel;
				...
				mylabel:

			문법적으로 가능하지만
			현대 C++에서는 보통 피하는 편이다.

			왜냐하면:
				- 흐름 추적이 어려워지고
				- 가독성이 나빠지고
				- 유지보수가 힘들어지기 때문이다

			따라서 특별한 이유가 없다면
			break, continue, return, 함수 분리 등으로 대체하는 편이 좋다.


			=======================================================================================
			4. 핵심 요약
			=======================================================================================

				- break    : 반복문/switch 즉시 종료
				- continue : 현재 반복만 건너뛰고 다음 반복
				- goto     : 레이블로 무조건 점프, 일반적으로 지양
		*/


		//=========================================================================================
		// [테스트 예제 1] break
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] break" << std::endl;
			std::cout << "==================================================" << std::endl;

			for (int n = 10; n > 0; --n)
			{
				std::cout << n << ", ";

				if (n == 3)
				{
					std::cout << "countdown aborted!";
					break;
				}
			}

			std::cout << std::endl << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 2] continue
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] continue" << std::endl;
			std::cout << "==================================================" << std::endl;

			for (int n = 10; n > 0; --n)
			{
				if (n == 5)
					continue;

				std::cout << n << ", ";
			}

			std::cout << "liftoff!" << std::endl;
			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 3] goto
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 3] goto" << std::endl;
			std::cout << "==================================================" << std::endl;

			int n = 10;

		mylabel:
			std::cout << n << ", ";
			--n;

			if (n > 0)
				goto mylabel;

			std::cout << "liftoff!" << std::endl;
			std::cout << std::endl;
		}

		system("pause");
	}

