	void selection_statements()
	{
		/*
			📚 선택문: if 와 else

			if 문은 조건이 참일 때만
			특정 문장 또는 블록을 실행하는 선택문이다.

			기본 형태:

				if (condition)
					statement;

			여기서 condition 이 true 이면 statement 실행,
			false 이면 무시하고 다음으로 넘어간다.


			=======================================================================================
			1. if 문
			=======================================================================================

			예:
				if (x == 100)
					std::cout << "x is 100";

			이 경우 x가 100일 때만 출력한다.

			조건이 거짓이면 아무 일도 하지 않는다.


			=======================================================================================
			2. 여러 문장을 실행하려면 { } 필요
			=======================================================================================

			if 본문에 여러 문장을 넣고 싶다면
			중괄호로 묶어야 한다.

			예:
				if (x == 100)
				{
					std::cout << "x is ";
					std::cout << x;
				}

			중괄호가 없으면 첫 문장만 if에 포함된다.


			=======================================================================================
			3. else
			=======================================================================================

			조건이 거짓일 때 실행할 대체 경로를 만들려면 else를 쓴다.

			예:
				if (x == 100)
					std::cout << "x is 100";
				else
					std::cout << "x is not 100";


			=======================================================================================
			4. else if
			=======================================================================================

			여러 조건을 순차적으로 검사하려면 else if를 이어 붙인다.

			예:
				if (x > 0)
					...
				else if (x < 0)
					...
				else
					...

			이렇게 하면
				양수 / 음수 / 0
			처럼 여러 경우를 나눌 수 있다.


			=======================================================================================
			5. 핵심 요약
			=======================================================================================

				- if 는 조건이 참일 때만 실행
				- else 는 조건이 거짓일 때 실행
				- else if 는 여러 조건 분기
				- 여러 문장은 { } 로 묶는 것이 안전하다
		*/


		//=========================================================================================
		// [테스트 예제 1] 기본 if
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 기본 if" << std::endl;
			std::cout << "==================================================" << std::endl;

			int x = 100;

			if (x == 100)
				std::cout << "x is 100" << std::endl;

			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 2] if-else
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] if-else" << std::endl;
			std::cout << "==================================================" << std::endl;

			int x = 50;

			if (x == 100)
				std::cout << "x is 100" << std::endl;
			else
				std::cout << "x is not 100" << std::endl;

			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 3] else if 체인
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 3] else if 체인" << std::endl;
			std::cout << "==================================================" << std::endl;

			int x = -10;

			if (x > 0)
				std::cout << "x is positive" << std::endl;
			else if (x < 0)
				std::cout << "x is negative" << std::endl;
			else
				std::cout << "x is 0" << std::endl;

			std::cout << std::endl;
		}

		system("pause");
	}

