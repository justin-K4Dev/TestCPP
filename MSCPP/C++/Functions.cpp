	// Recursivity example
	long factorial(long a)
	{
		if (a > 1)
			return (a * factorial(a - 1));
		else
			return 1;
	}

	void recursivity()
	{
		/*
			📚 재귀 (Recursivity / Recursion)

			재귀란 함수가 자기 자신을 다시 호출하는 성질을 말한다.

			즉, 함수 안에서 같은 함수를 호출하는 방식이다.

			재귀는 어떤 문제를
			"더 작은 같은 문제"로 나눌 수 있을 때 매우 유용하다.

			대표 예:
				- 팩토리얼
				- 트리 순회
				- DFS
				- 분할 정복
				- 백트래킹

			하지만 재귀는 반드시 종료 조건(base case)이 있어야 한다.
			그렇지 않으면 무한 호출이 발생한다.


			=======================================================================================
			1. 팩토리얼 예제
			=======================================================================================

			수학적으로 팩토리얼은 다음과 같다.

				n! = n * (n-1) * (n-2) * ... * 1

			예:
				5! = 5 * 4 * 3 * 2 * 1 = 120

			이걸 재귀식으로 쓰면:

				n! = n * (n-1)!
				1! = 1

			즉, 문제를 더 작은 같은 문제로 바꾼 것이다.


			=======================================================================================
			2. 현재 factorial 함수 의미
			=======================================================================================

			현재 함수는 다음과 같다.

				long factorial(long a)
				{
					if (a > 1)
						return a * factorial(a - 1);
					else
						return 1;
				}

			의미:
				- a가 1보다 크면
					a * factorial(a-1)
				- a가 1 이하이면
					1 반환

			즉, 9! 를 구할 때 내부적으로는

				9 * factorial(8)
				8 * factorial(7)
				7 * factorial(6)
				...
				1

			처럼 계속 들어간 뒤,
			반대로 결과가 쌓이면서 올라온다.


			=======================================================================================
			3. 종료 조건이 왜 중요한가?
			=======================================================================================

			재귀에는 반드시 종료 조건이 필요하다.

			이 예제에서는:

				if (a > 1)
					...
				else
					return 1;

			이 부분이 종료 조건이다.

			이게 없으면 factorial은 계속 자기 자신을 호출해서
			스택 오버플로우가 발생할 수 있다.


			=======================================================================================
			4. 핵심 요약
			=======================================================================================

				- 재귀는 함수가 자기 자신을 호출하는 방식이다.
				- 큰 문제를 작은 같은 문제로 나눌 때 유용하다.
				- 반드시 종료 조건이 있어야 한다.
				- 팩토리얼은 대표적인 재귀 예제이다.
		*/


		//=========================================================================================
		// [테스트 예제 1] factorial 기본 호출
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] factorial 기본 호출" << std::endl;
			std::cout << "==================================================" << std::endl;

			long number = 9;
			std::cout << number << "! = " << factorial(number) << std::endl;
			std::cout << std::endl;

			/*
				예상 출력:
					9! = 362880
			*/
		}


		//=========================================================================================
		// [테스트 예제 2] 작은 값들 확인
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] 작은 값들 확인" << std::endl;
			std::cout << "==================================================" << std::endl;

			for (long i = 1; i <= 5; ++i)
			{
				std::cout << i << "! = " << factorial(i) << std::endl;
			}

			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 3] 재귀 흐름 설명
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 3] 재귀 흐름 설명" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::cout << "factorial(4)" << std::endl;
			std::cout << "= 4 * factorial(3)" << std::endl;
			std::cout << "= 4 * 3 * factorial(2)" << std::endl;
			std::cout << "= 4 * 3 * 2 * factorial(1)" << std::endl;
			std::cout << "= 4 * 3 * 2 * 1" << std::endl;
			std::cout << "= 24" << std::endl;
			std::cout << std::endl;
		}

		system("pause");
	}

