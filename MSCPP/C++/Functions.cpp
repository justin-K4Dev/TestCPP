	void declaring_functions()
	{
		/*
			📚 함수 선언 (Declaring functions)

			C++에서는 식별자를 사용하기 전에
			먼저 선언(declaration)되어 있어야 한다.

			이 규칙은 함수에도 그대로 적용된다.

			즉, 어떤 함수를 호출하려면
			그 함수는 최소한 "이름, 반환형, 매개변수 타입" 정도는
			미리 알려져 있어야 한다.

			이때 사용하는 것이 함수 선언, 즉 함수 원형(prototype)이다.

			예:
				void even(int x);
				void odd(int x);

			이 선언은
			아직 함수 본문은 없지만,
			이런 형태의 함수가 어딘가에 존재한다는 정보를 컴파일러에 알려준다.


			=======================================================================================
			1. 선언과 정의의 차이
			=======================================================================================

			선언(declaration)
				함수의 존재와 형태를 알림

			정의(definition)
				함수의 실제 코드까지 작성

			예:
				void odd(int x);   // 선언
				void odd(int x)    // 정의 시작
				{
					...
				}


			=======================================================================================
			2. 왜 필요한가?
			=======================================================================================

			함수 호출 시점보다 정의가 뒤에 있으면
			컴파일러는 아직 그 함수를 모른다.

			그래서 선언이 필요하다.

			특히 서로가 서로를 호출하는 함수에서는
			선언이 거의 필수적이다.

			예:
				odd() 안에서 even() 호출
				even() 안에서 odd() 호출

			이 경우 둘 다 서로를 알아야 하므로
			앞쪽에 선언을 두는 것이 자연스럽다.


			=======================================================================================
			3. 매개변수 이름은 선언에서 생략 가능
			=======================================================================================

			선언에서는 매개변수 이름을 생략할 수도 있다.

			예:
				int protofunction(int first, int second);
				int protofunction(int, int);

			둘 다 가능하다.

			하지만 이름을 적어 주는 편이
			가독성은 더 좋다.


			=======================================================================================
			4. 핵심 요약
			=======================================================================================

				- 함수는 사용 전에 선언되어야 한다.
				- 선언은 함수 원형(prototype)이다.
				- 정의는 실제 함수 본문까지 포함한다.
				- 서로 호출하는 함수들에서는 선언이 특히 중요하다.
		*/


		//=========================================================================================
		// [테스트 예제 1] 선언된 함수 호출
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 함수 선언 후 호출" << std::endl;
			std::cout << "==================================================" << std::endl;

			int i = 0;
			do
			{
				std::cout << "Please, enter number (0 to exit): ";
				std::cin >> i;
				odd(i);
			} while (i != 0);

			std::cout << std::endl;

			/*
				예상 동작:
					9   -> It is odd.
					6   -> It is even.
					0   -> It is even.
			*/
		}


		//=========================================================================================
		// [테스트 예제 2] 선언의 의미 설명
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] 함수 선언의 의미" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::cout << "void odd(int x); 와 void even(int x); 는 함수 원형(prototype)이다." << std::endl;
			std::cout << "컴파일러는 이를 통해 함수 이름, 반환형, 인자 타입을 미리 알 수 있다." << std::endl;
			std::cout << std::endl;
		}

		system("pause");
	}

