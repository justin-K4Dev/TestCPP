	typedef  unsigned long long ULONG64;

	ULONG64 fibonachi_tail_x64(ULONG64 n, ULONG64 res, ULONG64 next)
	{
		if (n == 0) {
			return res;
		}

		return fibonachi_tail_x64(n - 1, next, res + next);
	}

	void fibonachi()
	{
		/*
			📚 피보나치와 테일 재귀 (Fibonacci and tail recursion)

			피보나치 수열은 대표적인 재귀 예제이다.

			일반적으로 피보나치 수열은 다음처럼 정의된다.

				F(0) = 0
				F(1) = 1
				F(n) = F(n-1) + F(n-2)

			그런데 이 정의를 그대로 재귀로 구현하면
			중복 호출이 매우 많아져서 비효율적이다.

			그래서 보통은:

				- 반복문
				- 메모이제이션
				- DP
				- 꼬리 재귀 스타일

			등으로 개선한다.

			현재 함수 `fibonachi_tail_x64()` 는
			누적값(accumulator)을 전달하는 꼬리 재귀 형태이다.


			=======================================================================================
			1. 현재 함수 의미
			=======================================================================================

				ULONG64 fibonachi_tail_x64(ULONG64 n, ULONG64 res, ULONG64 next)

			여기서 의미는 대략 다음과 같다.

				n
					남은 단계 수

				res
					현재 피보나치 값

				next
					다음 피보나치 값

			재귀 호출 시:

				return fibonachi_tail_x64(n - 1, next, res + next);

			즉,
				현재값 -> 다음값으로 이동
				다음값 -> 현재+다음 으로 갱신

			하는 식으로 한 단계씩 전진한다.

			그리고 이 재귀 호출이 함수의 마지막 작업이므로
			테일 재귀 형태이다.


			=======================================================================================
			2. 주의: 이것도 TCO 보장은 아니다
			=======================================================================================

			이 함수는 테일 재귀 형태이지만,
			C++에서 실제로 Tail Call Optimization 이 적용될지는
			역시 보장되지 않는다.

			즉:
				형태는 tail-recursive
				최적화는 구현 의존

			이다.


			=======================================================================================
			3. 두 번째 예제의 의미
			=======================================================================================

			두 번째 블록에서는 함수 포인터를 통해 호출한다.

				ULONG64(*ptr)(ULONG64, ULONG64, ULONG64) = NULL;
				ptr = &fibonachi_tail_x64;
				res = ptr(40, 0, 1);

			이건 함수 포인터 호출 예시이기도 하다.

			다만 함수 포인터를 거친 호출은
			직접 호출과 비교했을 때
			컴파일러 최적화 가능성에 차이를 줄 수도 있다.

			즉, 이런 형태는 TCO 관찰 실험용으로도 볼 수 있다.


			=======================================================================================
			4. 핵심 요약
			=======================================================================================

				- 일반 피보나치 재귀는 비효율적일 수 있다
				- 현재 구현은 누적값을 전달하는 꼬리 재귀 형태이다
				- 하지만 C++에서 실제 tail-call 최적화는 보장되지 않는다
				- 함수 포인터 호출은 최적화 관찰 시 변수 요소가 될 수 있다
		*/


		//=========================================================================================
		// [테스트 예제 1] 직접 호출
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 피보나치 테일 재귀 직접 호출" << std::endl;
			std::cout << "==================================================" << std::endl;

			ULONG64 a = 40;
			ULONG64 res = fibonachi_tail_x64(a, 0, 1);

			std::cout << "fibonachi_tail_x64(40, 0, 1) = " << res << std::endl;
			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 2] 함수 포인터를 통한 호출
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] 함수 포인터를 통한 호출" << std::endl;
			std::cout << "==================================================" << std::endl;

			volatile bool a = true;
			ULONG64 res = 0;
			ULONG64(*ptr)(ULONG64 n, ULONG64 res, ULONG64 next) = NULL;

			if (a)
			{
				ptr = &fibonachi_tail_x64;
			}

			res = ptr(40, 0, 1);

			std::cout << "ptr(40, 0, 1) = " << res << std::endl;
			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 3] 꼬리 재귀 형태 설명
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 3] 피보나치 테일 재귀 형태 설명" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::cout << "return fibonachi_tail_x64(n - 1, next, res + next);" << std::endl;
			std::cout << "이 호출은 함수의 마지막 작업이므로 테일 콜 형태이다." << std::endl;
			std::cout << "하지만 실제 최적화 여부는 컴파일러와 빌드 옵션에 따라 달라질 수 있다." << std::endl;
			std::cout << std::endl;
		}

		system("pause");
	}

