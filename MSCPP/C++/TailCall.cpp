	void tail_call_what()
	{
		/*
			📚 테일 콜 (Tail Call)

			함수의 마지막 동작이 다른 함수 호출인 경우를 말한다.

			즉, 어떤 함수를 호출한 뒤
			그 결과에 추가 계산을 하지 않고
			그대로 바로 반환하는 형태이다.

			예:
				return some_function(x);

			이런 형태는 테일 콜이다.

			반면 다음은 테일 콜이 아니다.

				return 1 + some_function(x);

			왜냐하면 some_function(x)를 호출한 뒤에도
			1을 더하는 추가 작업이 남아 있기 때문이다.


			=======================================================================================
			1. 테일 콜의 핵심
			=======================================================================================

			테일 콜은 함수의 마지막 단계가 함수 호출이라는 점이 핵심이다.

			즉:
				- 호출 후 할 일이 없음
				- 호출 결과를 그대로 반환
				- 이론적으로는 현재 스택 프레임 재사용 가능

			이 때문에 컴파일러가 조건이 맞으면
			테일 콜 최적화(Tail Call Optimization, TCO)를 적용할 가능성이 있다.


			=======================================================================================
			2. 중요한 주의사항
			=======================================================================================

			C++ 표준은 컴파일러가
			테일 콜 최적화를 반드시 해야 한다고 요구하지 않는다.

			즉:
				- 테일 콜 형태여도
				- 실제 최적화는 안 될 수 있다

			특히:
				- 디버그 빌드
				- 최적화 꺼짐
				- 호출 규약 제약
				- ABI 제약
				- 컴파일러 구현 차이

			등에 따라 결과가 달라질 수 있다.

			따라서 "테일 재귀로 짰으니 무조건 스택이 안 쌓인다"라고 생각하면 안 된다.


			=======================================================================================
			3. 핵심 요약
			=======================================================================================

				- 테일 콜은 함수의 마지막 작업이 함수 호출인 형태
				- 테일 재귀는 자기 자신을 테일 콜하는 형태
				- 최적화 여부는 컴파일러가 결정하며 보장되지 않는다
		*/


		//=========================================================================================
		// [테스트 예제 1] 테일 콜 vs 논테일 콜 설명
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 테일 콜 vs 논테일 콜 설명" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::cout << "테일 콜 예: return func(x);" << std::endl;
			std::cout << "논테일 콜 예: return 1 + func(x);" << std::endl;
			std::cout << "차이는 호출 이후 추가 작업이 남아 있느냐이다." << std::endl;
			std::cout << std::endl;
		}

		system("pause");
	}

