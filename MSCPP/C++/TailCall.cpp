	// Multiplying by two
	long times_two_hardware(long value)
	{
		return value * 2;
	}

	long times_two_loop(long value)
	{
		long ret = 0;

		for (long i = 0; i < value; ++i)
		{
			ret += 2;
		}

		return ret;
	}

	long times_two_naive_recursive(long value)
	{
		if (value == 0)
		{
			return 0;
		}
		else
		{
			return 2 + times_two_naive_recursive(value - 1);
		}
	}


	// Tail call style recursion
	long times_two_recursive_impl(long total, long counter)
	{
		if (counter == 0)
		{
			return total;
		}
		else
		{
			return times_two_recursive_impl(total + 2, counter - 1);
		}
	}

	long times_two_recursive(long value)
	{
		return times_two_recursive_impl(0, value);
	}


	// Trampoline-style manual tail call handling
	struct Answer;
	typedef Answer(*impl_fn_type)(long, long);

	struct FnPlusArgs
	{
		impl_fn_type fn_;
		long arg1_;
		long arg2_;

		FnPlusArgs(
			impl_fn_type fn,
			long arg1,
			long arg2
		);

		Answer operator()();
	};

	impl_fn_type null_fn = NULL;
	FnPlusArgs null_fn_plus_args(null_fn, 0, 0);

	struct Answer
	{
		bool finished_;
		FnPlusArgs tail_call_;
		long value_;

		Answer(bool finished, FnPlusArgs tail_call, long value);
	};


	FnPlusArgs::FnPlusArgs(
		impl_fn_type fn,
		long arg1,
		long arg2
	)
		: fn_(fn)
		, arg1_(arg1)
		, arg2_(arg2)
	{
	}

	Answer FnPlusArgs::operator()()
	{
		return fn_(arg1_, arg2_);
	}


	Answer::Answer(bool finished, FnPlusArgs tail_call, long value)
		: finished_(finished)
		, tail_call_(tail_call)
		, value_(value)
	{
	}


	// The Trampoline
	long trampoline(Answer answer)
	{
		while (!answer.finished_)
		{
			answer = answer.tail_call_();
		}
		return answer.value_;
	}

	Answer times_two_tail_call_impl(long acc, long i)
	{
		if (i == 0)
		{
			return Answer(true, null_fn_plus_args, acc);
		}
		else
		{
			return Answer(
				false,
				FnPlusArgs(
					times_two_tail_call_impl,
					acc + 2,
					i - 1
				),
				0
			);
		}
	}

	long times_two_tail_call(long n)
	{
		return trampoline(
			Answer(
				false,
				FnPlusArgs(times_two_tail_call_impl, 0, n),
				0
			)
		);
	}

	void tail_call()
	{
		/*
			📚 테일 콜과 테일 재귀 (Tail Call / Tail Recursion)

			이 예제는 같은 "2배 계산"을 여러 방식으로 구현해서
			테일 재귀와 트램펄린 구조를 비교해 보는 코드이다.

			구현 방식은 다음과 같다.

				1) 하드웨어 곱셈
					times_two_hardware()

				2) 반복문
					times_two_loop()

				3) 일반 재귀
					times_two_naive_recursive()

				4) 테일 재귀 형태
					times_two_recursive()

				5) 트램펄린(Trampoline) 방식
					times_two_tail_call()


			=======================================================================================
			1. 가장 단순한 방식: 하드웨어 곱셈
			=======================================================================================

				return value * 2;

			이 방식이 가장 직접적이다.
			CPU의 산술 연산을 바로 사용한다.

			성능 면에서는 대부분 이 방식이 가장 단순하고 효율적이다.


			=======================================================================================
			2. 반복문 방식
			=======================================================================================

			times_two_loop()는
			2를 value번 더하는 방식이다.

			예:
				value = 5
				-> 2 + 2 + 2 + 2 + 2 = 10

			논리 설명용 예제로는 괜찮지만
			실제로는 곱셈보다 비효율적이다.


			=======================================================================================
			3. 일반 재귀 (naive recursive)
			=======================================================================================

			times_two_naive_recursive():

				return 2 + times_two_naive_recursive(value - 1);

			이 함수는 재귀 호출 뒤에
			+ 2 라는 추가 작업이 남아 있다.

			즉, 테일 콜이 아니다.

			왜냐하면 호출 결과를 받은 뒤
			계산을 더 해야 하기 때문이다.

			따라서 일반적으로 스택 프레임이 계속 누적된다.


			=======================================================================================
			4. 테일 재귀 형태
			=======================================================================================

			times_two_recursive_impl():

				return times_two_recursive_impl(total + 2, counter - 1);

			이 함수는 재귀 호출이 마지막 작업이다.
			호출 뒤에 더 할 일이 없다.

			즉, 테일 콜 형태이다.

			이론적으로는 컴파일러가
			현재 프레임을 재사용해서
			반복문처럼 최적화할 수 있다.

			하지만 다시 강조하면:
			C++에서 이 최적화는 보장되지 않는다.

			즉, 형태는 tail-recursive 이지만
			실행 시 실제 TCO 적용 여부는 별도 문제이다.


			=======================================================================================
			5. 트램펄린(Trampoline) 방식
			=======================================================================================

			times_two_tail_call() 쪽은
			컴파일러의 꼬리 호출 최적화에 의존하지 않고,
			직접 "다음 호출 정보"를 객체로 반환한 뒤
			trampoline() 루프가 이를 계속 실행하는 구조이다.

			즉:
				- 재귀 호출을 직접 깊게 타지 않고
				- "다음 호출"을 데이터처럼 표현
				- while 루프로 반복 실행

			이 방식은 함수형 프로그래밍에서 종종 보이는
			트램펄린 기법이다.

			따라서 이것은 "컴파일러 TCO"라기보다
			"사용자 코드로 만든 수동 tail-call 처리"라고 보는 것이 더 정확하다.


			=======================================================================================
			6. 핵심 비교
			=======================================================================================

				times_two_hardware
					가장 직접적

				times_two_loop
					반복문 기반

				times_two_naive_recursive
					재귀 호출 뒤에 추가 연산 존재
					-> 테일 콜 아님

				times_two_recursive
					테일 재귀 형태
					-> 최적화 가능성은 있으나 보장 없음

				times_two_tail_call
					트램펄린 기반
					-> 스택 증가를 수동 회피하는 구조


			=======================================================================================
			7. 핵심 요약
			=======================================================================================

				- 테일 재귀는 재귀 호출이 마지막 작업인 형태
				- 일반 재귀는 호출 뒤 추가 작업이 남는다
				- C++에서 TCO는 보장되지 않는다
				- 트램펄린은 수동으로 재귀를 반복문처럼 바꾸는 기법이다
		*/


		//=========================================================================================
		// [테스트 예제 1] 여러 구현 결과 비교
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 여러 구현 결과 비교" << std::endl;
			std::cout << "==================================================" << std::endl;

			long value = 10;

			std::cout << "times_two_hardware(" << value << ")        = " << times_two_hardware(value) << std::endl;
			std::cout << "times_two_loop(" << value << ")            = " << times_two_loop(value) << std::endl;
			std::cout << "times_two_naive_recursive(" << value << ") = " << times_two_naive_recursive(value) << std::endl;
			std::cout << "times_two_recursive(" << value << ")       = " << times_two_recursive(value) << std::endl;
			std::cout << "times_two_tail_call(" << value << ")       = " << times_two_tail_call(value) << std::endl;
			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 2] naive recursion 과 tail recursion 차이 설명
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] naive recursion 과 tail recursion 차이" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::cout << "naive recursion : return 2 + recursive(...);" << std::endl;
			std::cout << "tail recursion  : return recursive(...);" << std::endl;
			std::cout << "즉, 재귀 호출 뒤에 추가 작업이 남아 있으면 꼬리 호출이 아니다." << std::endl;
			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 3] 트램펄린 설명
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 3] 트램펄린 설명" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::cout << "trampoline() 은 다음 호출 정보를 Answer 로 받아 while 루프로 계속 실행한다." << std::endl;
			std::cout << "즉, 깊은 재귀 호출 대신 반복 구조로 바꾸어 스택 사용을 줄이는 기법이다." << std::endl;
			std::cout << std::endl;
		}

		system("pause");
	}

