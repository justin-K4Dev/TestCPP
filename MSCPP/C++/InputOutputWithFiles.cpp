	void input_output_with_files()
	{
		/*
			📚 파일을 이용한 입력 / 출력 (input / output with files)

			C++에서는 파일과의 입출력을 위해
			스트림(stream) 기반 클래스를 제공한다.

			대표적으로 다음 3가지 클래스가 있다.

				- std::ofstream
					파일에 쓰기(write) 위한 스트림

				- std::ifstream
					파일에서 읽기(read) 위한 스트림

				- std::fstream
					파일 읽기/쓰기를 모두 지원하는 스트림

			이 클래스들은 cin, cout 과 같은 스트림 계열과 연결된 개념이다.

			즉:
				- cout 은 화면으로 출력하는 스트림
				- ifstream / ofstream / fstream 은 파일로 입출력하는 스트림

			이라고 이해하면 된다.

			그래서 사용법도 cout / cin 과 매우 비슷하다.
			차이는 "물리적인 파일과 연결해야 한다"는 점이다.


			=======================================================================================
			1. 기본 개념
			=======================================================================================

			파일 스트림 객체는
			프로그램 안에서 파일을 다루는 통로 역할을 한다.

			예:
				std::ofstream myfile;
				myfile.open("example.txt");
				myfile << "Writing this to a file.\n";
				myfile.close();

			이 코드는 다음 과정을 수행한다.

				1) 출력용 파일 스트림 객체 생성
				2) example.txt 파일 열기
				3) 문자열 출력
				4) 파일 닫기

			즉, cout 처럼 << 연산자를 쓰지만
			대상은 화면이 아니라 파일이다.


			=======================================================================================
			2. 핵심 요약
			=======================================================================================

				- ofstream : 파일 쓰기
				- ifstream : 파일 읽기
				- fstream  : 파일 읽기 + 쓰기
				- 사용 방식은 cin / cout 과 유사하다
				- 실제 파일과 연결하려면 open() 이 필요하다
		*/


		//=========================================================================================
		// [테스트 예제 1] 파일에 한 줄 쓰기
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 파일에 한 줄 쓰기" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::ofstream myfile;
			myfile.open("example.txt");

			if (myfile.is_open())
			{
				myfile << "Writing this to a file.\n";
				myfile.close();
				std::cout << "example.txt 파일에 쓰기 완료" << std::endl;
			}
			else
			{
				std::cout << "파일 열기 실패" << std::endl;
			}

			std::cout << std::endl;

			/*
				생성 파일:
					example.txt

				예상 내용:
					Writing this to a file.
			*/
		}

		system("pause");
	}

