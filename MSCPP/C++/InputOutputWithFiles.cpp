	void text_files()
	{
		/*
			📚 텍스트 파일 (Text files)

			텍스트 파일은 std::ios::binary 플래그 없이 여는 파일이다.

			이런 파일은 사람이 읽을 수 있는 문자 기반 데이터 저장에 적합하다.

			예:
				- 로그 파일
				- 설정 파일
				- CSV 일부
				- 일반 문서형 데이터

			텍스트 파일에서는
			출력 시 << 연산자,
			입력 시 >>, getline() 등을
			콘솔 스트림처럼 사용할 수 있다.


			=======================================================================================
			1. 텍스트 파일 쓰기
			=======================================================================================

			ofstream 에 << 연산자를 사용하면
			cout 처럼 파일에 텍스트를 기록할 수 있다.


			=======================================================================================
			2. 텍스트 파일 읽기
			=======================================================================================

			ifstream 과 getline() 을 사용하면
			파일 내용을 줄 단위로 읽을 수 있다.

			예:
				while (std::getline(myfile, line))
				{
					...
				}

			getline() 의 반환값은 스트림 참조이며,
			while 조건식에서 성공 여부로 평가된다.

			즉:
				- 읽기 성공 -> true
				- EOF 또는 오류 -> false


			=======================================================================================
			3. 핵심 요약
			=======================================================================================

				- 텍스트 파일은 문자 기반 파일
				- 쓰기는 << 연산자 사용 가능
				- 읽기는 getline() 과 함께 자주 사용
				- 콘솔 입출력과 유사한 방식으로 다룰 수 있다
		*/


		//=========================================================================================
		// [테스트 예제 1] 텍스트 파일 쓰기
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 텍스트 파일 쓰기" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::ofstream myfile("example.txt");

			if (myfile.is_open())
			{
				myfile << "This is a line.\n";
				myfile << "This is another line.\n";
				myfile.close();

				std::cout << "example.txt 쓰기 완료" << std::endl;
			}
			else
			{
				std::cout << "Unable to open file" << std::endl;
			}

			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 2] 텍스트 파일 읽기
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] 텍스트 파일 읽기" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::string line;
			std::ifstream myfile("example.txt");

			if (myfile.is_open())
			{
				while (std::getline(myfile, line))
				{
					std::cout << line << '\n';
				}
				myfile.close();
			}
			else
			{
				std::cout << "Unable to open file" << std::endl;
			}

			std::cout << std::endl;
		}

		system("pause");
	}

