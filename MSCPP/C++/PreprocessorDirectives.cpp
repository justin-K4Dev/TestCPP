	void line_control()
	{
		/*
			📚 라인 제어 (#line)

			#line 지시문은 이후 코드의
			"줄 번호"와 "파일 이름"이 무엇으로 보일지를
			전처리기 수준에서 바꾸는 기능이다.

			형식:

				#line number "filename"

			의미:
				- 다음 코드 줄의 번호를 number 로 간주
				- 에러 메시지에 표시될 파일 이름을 filename 으로 간주

			즉, 컴파일 오류가 발생했을 때
			어느 파일 몇 줄에서 발생한 것으로 보일지 조정할 수 있다.

			이 기능은 보통 다음 상황에서 사용될 수 있다.

				- 코드 생성기(generator)가 만든 코드
				- 변환된 소스의 원본 위치 추적
				- 디버깅용 위치 매핑


			=======================================================================================
			1. 사용 예
			=======================================================================================

				#line 20 "generated_file"
				int a?;

			이 코드는 문법 오류를 발생시키는데,
			컴파일러는 에러를 "generated_file", line 20 으로 보고할 수 있다.


			=======================================================================================
			2. 핵심 요약
			=======================================================================================

				- #line 은 줄 번호와 파일 이름을 재정의한다.
				- 컴파일 에러 메시지에 보이는 위치를 바꿀 수 있다.
				- 주로 코드 생성기나 변환 도구에서 의미가 있다.
		*/


		//=========================================================================================
		// [테스트 예제 1] __LINE__ 변화 확인
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] #line 과 __LINE__ 확인" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::cout << "현재 __LINE__ = " << __LINE__ << std::endl;

#line 200 "virtual_generated_file.cpp"

			std::cout << "변경 후 __LINE__ = " << __LINE__ << std::endl;
			std::cout << "변경 후 __FILE__ = " << __FILE__ << std::endl;

#line 1 "restored_file.cpp"

			std::cout << "다시 변경 후 __LINE__ = " << __LINE__ << std::endl;
			std::cout << "다시 변경 후 __FILE__ = " << __FILE__ << std::endl;
			std::cout << std::endl;
		}

		system("pause");
	}

