	void preprocessor_directives()
	{
		/*
			📚 전처리기 지시문 (Preprocessor Directives)

			전처리기 지시문은 소스 코드에서 # 으로 시작하는 특별한 줄이다.

			이것들은 C++ 문장이 아니라
			컴파일 전에 먼저 실행되는 전처리기(preprocessor)에 대한 명령이다.

			즉, 전처리기는 실제 컴파일이 시작되기 전에
			소스 코드를 먼저 훑어보면서 다음과 같은 작업을 수행한다.

				- 매크로 치환 (#define)
				- 조건부 컴파일 (#if, #ifdef ...)
				- 파일 포함 (#include)
				- 오류 강제 발생 (#error)
				- 컴파일러 힌트 (#pragma)

			즉, 전처리기는 "코드를 컴파일하기 전에 코드를 바꾸는 단계"라고 보면 된다.


			=======================================================================================
			1. 전처리기 지시문의 특징
			=======================================================================================

			전처리기 지시문은 한 줄 단위로 끝난다.

			즉, 줄 끝 개행 문자에서 지시문이 종료된다.

			예:
				#define SIZE 100

			이 한 줄 전체가 하나의 전처리기 지시문이다.

			세미콜론(;)은 필요하지 않다.

			즉:
				#define SIZE 100;
			처럼 쓰는 것이 아니라

				#define SIZE 100
			처럼 쓴다.


			=======================================================================================
			2. 여러 줄로 이어 쓰기
			=======================================================================================

			전처리기 지시문은 기본적으로 한 줄만 유효하지만,
			줄 끝에 백슬래시(\)를 붙이면 다음 줄까지 이어질 수 있다.

			예:
				#define PRINT_SUM(a,b) \
					std::cout << ((a) + (b)) << std::endl;

			이렇게 하면 매크로 정의를 여러 줄로 보기 좋게 쓸 수 있다.


			=======================================================================================
			3. 전처리기의 본질
			=======================================================================================

			전처리기는 C++ 문법을 제대로 이해하는 것이 아니라,
			기본적으로는 "텍스트 치환" 중심으로 동작한다.

			즉:
				- 코드를 실행하는 것이 아님
				- 타입 검사도 하지 않음
				- 단순히 코드를 바꾸거나 포함시키는 역할

			그래서 강력하지만,
			과도하게 사용하면 디버깅과 유지보수가 어려워질 수 있다.


			=======================================================================================
			4. 핵심 요약
			=======================================================================================

				- 전처리기 지시문은 # 으로 시작한다.
				- 컴파일 전에 먼저 처리된다.
				- 한 줄 단위가 기본이다.
				- 세미콜론은 필요 없다.
				- 필요하면 \ 로 여러 줄 연결 가능하다.
		*/


		//=========================================================================================
		// [테스트 예제 1] 여러 줄 매크로 예시
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 여러 줄 매크로 예시" << std::endl;
			std::cout << "==================================================" << std::endl;

#define PRINT_SUM(a,b) \
		std::cout << #a << " + " << #b << " = " << ((a) + (b)) << std::endl

			PRINT_SUM(3, 4);
			PRINT_SUM(10, 20);

#undef PRINT_SUM

			std::cout << std::endl;
		}

		system("pause");
	}

