	void macro_definitions()
	{
		/*
			📚 매크로 정의 (#define, #undef)

			#define 은 전처리기 매크로를 정의하는 지시문이다.

			기본 형식:

				#define 이름 치환내용

			전처리기는 이후 코드에서 해당 이름이 나오면
			치환내용으로 바꿔 넣는다.

			예:
				#define TABLE_SIZE 100

				int table[TABLE_SIZE];

			전처리기 이후에는 사실상 다음처럼 된다.

				int table[100];

			즉, 매크로는 "컴파일 전에 문자열처럼 치환되는 규칙"이라고 보면 된다.


			=======================================================================================
			1. 객체형 매크로
			=======================================================================================

			값 하나를 이름처럼 쓰고 싶을 때 사용한다.

			예:
				#define TABLE_SIZE 100

			이런 것은 상수처럼 보이지만
			실제로는 타입이 있는 C++ 상수가 아니라 텍스트 치환이다.

			현대 C++에서는 이런 용도로 보통
				const
				constexpr
			가 더 권장된다.


			=======================================================================================
			2. 함수형 매크로
			=======================================================================================

			매개변수를 받는 매크로도 만들 수 있다.

			예:
				#define getmax(a,b) ((a)>(b)?(a):(b))

			이것은 함수처럼 보이지만,
			실제로는 함수 호출이 아니라 전처리기 치환이다.

			주의:
				괄호를 충분히 잘 둘러주지 않으면
				연산 우선순위 문제로 버그가 생기기 쉽다.


			=======================================================================================
			3. #undef
			=======================================================================================

			정의한 매크로는 블록 범위와 상관없이 살아 있다.
			없애려면 #undef 를 사용해야 한다.

			예:
				#define SIZE 100
				#undef SIZE

			이후에는 SIZE 매크로가 더 이상 존재하지 않는다.


			=======================================================================================
			4. # 와 ## 연산자
			=======================================================================================

			함수형 매크로에서는 특수 연산자 #, ## 를 사용할 수 있다.

				#x
					인자를 문자열 리터럴로 바꿈

				a ## b
					두 토큰을 이어 붙임

			예:
				#define str(x) #x
				str(test)
					-> "test"

				#define glue(a,b) a##b
				glue(c,out)
					-> cout


			=======================================================================================
			5. 주의사항
			=======================================================================================

			매크로는 강력하지만 위험할 수 있다.

			이유:
				- 타입 검사 없음
				- 디버깅 어려움
				- 범위 개념 없음
				- 예상치 못한 치환 가능성
				- 함수처럼 보여도 실제 함수가 아님

			그래서 현대 C++에서는 가능한 한
				- constexpr
				- inline 함수
				- 템플릿
			등으로 대체하는 것이 좋다.


			=======================================================================================
			6. 핵심 요약
			=======================================================================================

				- #define 은 텍스트 치환 규칙을 만든다.
				- 함수형 매크로도 만들 수 있다.
				- #undef 로 매크로를 해제한다.
				- # 는 문자열화, ## 는 토큰 결합이다.
				- 복잡한 매크로는 가독성과 안정성을 떨어뜨릴 수 있다.
		*/


		//=========================================================================================
		// [테스트 예제 1] 함수형 매크로 기본 사용
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 함수형 매크로 기본 사용" << std::endl;
			std::cout << "==================================================" << std::endl;

#define getmax(a,b) ((a)>(b)?(a):(b))

			int x = 5;
			int y = getmax(x, 2);

			std::cout << "y = " << y << std::endl;
			std::cout << "getmax(7, x) = " << getmax(7, x) << std::endl;

#undef getmax

			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 2] #undef 사용
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] #undef 사용" << std::endl;
			std::cout << "==================================================" << std::endl;

#define TABLE_SIZE 100
			int table1[TABLE_SIZE];
			std::cout << "table1 size = " << sizeof(table1) / sizeof(table1[0]) << std::endl;

#undef TABLE_SIZE
#define TABLE_SIZE 200
			int table2[TABLE_SIZE];
			std::cout << "table2 size = " << sizeof(table2) / sizeof(table2[0]) << std::endl;

#undef TABLE_SIZE

			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 3] 문자열화 연산자 #
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 3] 문자열화 연산자 #" << std::endl;
			std::cout << "==================================================" << std::endl;

#define STR(x) #x
			std::cout << STR(test_macro_text) << std::endl;
#undef STR

			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 4] 토큰 결합 연산자 ##
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 4] 토큰 결합 연산자 ##" << std::endl;
			std::cout << "==================================================" << std::endl;

#define GLUE(a,b) std::a##b
			std::cout << "GLUE(c,out) 사용 예 -> ";
			GLUE(c, out) << "std::cout 로 출력됩니다." << std::endl;
#undef GLUE

			std::cout << std::endl;
		}

		system("pause");
	}

