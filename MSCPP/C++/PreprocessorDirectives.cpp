	void pragma_directive()
	{
		/*
			📚 pragma 지시문 (#pragma)

			#pragma 는 컴파일러에게 특정 옵션이나 힌트를 전달하는 지시문이다.

			중요:
				#pragma 는 표준화된 범위가 제한적이고,
				대부분은 컴파일러/플랫폼 의존적이다.

			즉:
				어떤 #pragma 는 MSVC 에서만 의미가 있고,
				어떤 것은 GCC/Clang 에서 다르게 동작할 수 있다.

			또한 지원하지 않는 pragma 인수는
			보통 무시되며 문법 오류가 나지 않는 경우가 많다.


			=======================================================================================
			1. 어디에 쓰는가?
			=======================================================================================

			예:
				- 경고 제어
				- 구조체 패킹 조절
				- once 포함 방지
				- 최적화 옵션 조정
				- region 정리

			MSVC 에서 자주 보는 예:
				#pragma once
				#pragma pack(push, 1)
				#pragma warning(disable: 4996)


			=======================================================================================
			2. 핵심 요약
			=======================================================================================

				- #pragma 는 컴파일러별 옵션/힌트를 전달한다.
				- 대부분 플랫폼/컴파일러 의존적이다.
				- 지원하지 않으면 무시되는 경우가 많다.
		*/


		//=========================================================================================
		// [테스트 예제 1] pragma 설명 출력
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] pragma 설명" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::cout << "대표 예: #pragma once" << std::endl;
			std::cout << "대표 예: #pragma pack(push, 1)" << std::endl;
			std::cout << "대표 예: #pragma warning(disable: 4996)" << std::endl;
			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 2] MSVC warning pragma 예시(설명용)
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] warning pragma 설명" << std::endl;
			std::cout << "==================================================" << std::endl;

#pragma warning(push)
#pragma warning(disable: 4127)
			if (true)
			{
				std::cout << "pragma warning 예시 구간" << std::endl;
			}
#pragma warning(pop)

			std::cout << std::endl;
		}

		system("pause");
	}

