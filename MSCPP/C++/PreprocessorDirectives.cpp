	void source_file_inclusion()
	{
		/*
			📚 소스 파일 포함 (#include)

			#include 는 지정한 헤더나 파일의 내용을
			현재 위치에 그대로 포함시키는 전처리기 지시문이다.

			즉, 전처리 단계에서:

				#include <iostream>

			이 나오면
			전처리기는 iostream 헤더의 내용을 현재 소스에 삽입한 것처럼 처리한다.


			=======================================================================================
			1. 두 가지 형태
			=======================================================================================

				#include <header>
					표준 라이브러리나 시스템 헤더용
					예:
						#include <iostream>

				#include "file"
					프로젝트 파일 또는 사용자 헤더용
					예:
						#include "MyHeader.h"

			보통 구현은:
				- "" 는 현재 경로를 먼저 찾고
				- 없으면 시스템 경로도 찾을 수 있다
			- <> 는 주로 시스템/표준 헤더 경로에서 찾는다


			=======================================================================================
			2. 왜 필요한가?
			=======================================================================================

			C++은 선언과 정의를 여러 파일로 나눠 관리하는 경우가 많다.
			그래서 필요한 선언을 현재 파일에 알려주기 위해
			헤더 포함이 필요하다.

			예:
				- std::cout 쓰려면 <iostream>
				- std::string 쓰려면 <string>


			=======================================================================================
			3. 핵심 요약
			=======================================================================================

				- #include 는 파일 내용을 현재 위치에 포함시킨다.
				- < > 는 보통 표준/시스템 헤더용
				- " " 는 보통 프로젝트 파일용
		*/


		//=========================================================================================
		// [테스트 예제 1] 표준 헤더 사용 예
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 표준 헤더 사용 예" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::string text = "iostream, string 헤더가 이미 포함되어 있다고 가정";
			std::cout << text << std::endl;
			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 2] include 개념 설명
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] #include 개념 설명" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::cout << "#include <header>  -> 시스템/표준 헤더" << std::endl;
			std::cout << "#include \"file\"    -> 프로젝트/사용자 파일" << std::endl;
			std::cout << std::endl;
		}

		system("pause");
	}

