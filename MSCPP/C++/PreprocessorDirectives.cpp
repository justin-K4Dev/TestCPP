	void predefined_macro_names()
	{
		/*
			📚 미리 정의된 매크로 이름 (Predefined Macro Names)

			C++ 컴파일러는 몇 가지 특별한 매크로를 기본 제공한다.

			대표적으로:

				__LINE__
					현재 소스 코드 줄 번호

				__FILE__
					현재 소스 파일 이름

				__DATE__
					컴파일 시작 날짜

				__TIME__
					컴파일 시작 시간

				__cplusplus
					현재 C++ 표준 지원 수준을 나타내는 값

				__STDC_HOSTED__
					호스티드 구현 여부(1 또는 0)

			이 값들은 디버깅, 로그, 빌드 정보 출력 등에 유용하다.


			=======================================================================================
			1. __cplusplus
			=======================================================================================

			__cplusplus 값은 지원하는 C++ 표준 수준을 나타낸다.

			대표 예:
				199711L
					C++98/03

				201103L
					C++11

				201402L
					C++14

				201703L
					C++17

				202002L
					C++20

			단, 실제 컴파일러는 완전히 표준값과 다르게 보일 수도 있다.
			특히 오래된 MSVC는 이 값을 기대와 다르게 주는 경우가 있었다.


			=======================================================================================
			2. 핵심 요약
			=======================================================================================

				- __LINE__ : 현재 줄 번호
				- __FILE__ : 현재 파일 이름
				- __DATE__ : 컴파일 날짜
				- __TIME__ : 컴파일 시간
				- __cplusplus : C++ 표준 지원 수준
		*/


		//=========================================================================================
		// [테스트 예제 1] 대표 미리 정의 매크로 출력
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] 대표 미리 정의 매크로 출력" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::cout << "현재 줄 번호(__LINE__) : " << __LINE__ << std::endl;
			std::cout << "현재 파일(__FILE__)    : " << __FILE__ << std::endl;
			std::cout << "컴파일 날짜(__DATE__)  : " << __DATE__ << std::endl;
			std::cout << "컴파일 시간(__TIME__)  : " << __TIME__ << std::endl;
			std::cout << "__cplusplus 값         : " << __cplusplus << std::endl;
			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 2] 로그 메시지 스타일 예시
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] 로그 메시지 스타일 예시" << std::endl;
			std::cout << "==================================================" << std::endl;

			std::cout << "[LOG] file=" << __FILE__
				<< ", line=" << __LINE__
				<< ", build=" << __DATE__ << " " << __TIME__
				<< std::endl;

			std::cout << std::endl;
		}

		system("pause");
	}

