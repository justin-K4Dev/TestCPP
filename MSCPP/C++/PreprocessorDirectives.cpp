	void conditional_inclusions()
	{
		/*
			📚 조건부 포함 (Conditional Inclusions)

			조건부 포함은 특정 조건이 참일 때만
			코드 일부를 컴파일하도록 하는 전처리기 기능이다.

			대표 지시문:

				#ifdef
				#ifndef
				#if
				#elif
				#else
				#endif

			이 기능은 보통 다음 상황에서 많이 사용된다.

				- 헤더 중복 포함 방지
				- 디버그/릴리즈 코드 분기
				- 플랫폼별 코드 분기
				- 특정 기능 활성화/비활성화


			=======================================================================================
			1. #ifdef / #ifndef
			=======================================================================================

			#ifdef NAME
				-> NAME 매크로가 정의되어 있으면 포함

			#ifndef NAME
				-> NAME 매크로가 정의되어 있지 않으면 포함

			예:
				#ifndef TABLE_SIZE
				#define TABLE_SIZE 100
				#endif

			이 코드는 TABLE_SIZE 가 없을 때만 100으로 정의한다.


			=======================================================================================
			2. #if / #elif / #else
			=======================================================================================

			이들은 "값 기반 조건 분기"에 사용된다.

			예:
				#if TABLE_SIZE > 200
				#elif TABLE_SIZE < 50
				#else
				#endif

			여기서 조건은 컴파일 타임 상수식이어야 하며,
			보통 매크로와 함께 쓴다.


			=======================================================================================
			3. defined 연산자
			=======================================================================================

			#if 에서는 defined 를 사용해
			특정 매크로가 정의되었는지도 검사할 수 있다.

			예:
				#if defined ARRAY_SIZE
				#elif !defined BUFFER_SIZE

			즉, #ifdef / #ifndef 를
			#if defined(...) 형태로도 표현할 수 있다.


			=======================================================================================
			4. 핵심 요약
			=======================================================================================

				- 조건부 포함은 특정 조건에서만 코드를 컴파일한다.
				- #ifdef 는 "정의되어 있으면"
				- #ifndef 는 "정의되어 있지 않으면"
				- #if 는 값 기반 조건식 사용
				- #endif 로 블록을 닫는다.
		*/


		//=========================================================================================
		// [테스트 예제 1] #ifndef 기본값 정의
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 1] #ifndef 기본값 정의" << std::endl;
			std::cout << "==================================================" << std::endl;

#ifndef TABLE_SIZE_EXAMPLE
#define TABLE_SIZE_EXAMPLE 100
#endif

			int table[TABLE_SIZE_EXAMPLE];
			std::cout << "TABLE_SIZE_EXAMPLE = "
				<< sizeof(table) / sizeof(table[0]) << std::endl;

#undef TABLE_SIZE_EXAMPLE

			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 2] #if / #elif / #else 분기
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 2] #if / #elif / #else 분기" << std::endl;
			std::cout << "==================================================" << std::endl;

#define TABLE_SIZE_TEST 30

#if TABLE_SIZE_TEST > 200
#undef TABLE_SIZE_TEST
#define TABLE_SIZE_TEST 200
#elif TABLE_SIZE_TEST < 50
#undef TABLE_SIZE_TEST
#define TABLE_SIZE_TEST 50
#else
#undef TABLE_SIZE_TEST
#define TABLE_SIZE_TEST 100
#endif

			int table[TABLE_SIZE_TEST];
			std::cout << "최종 TABLE_SIZE_TEST = "
				<< sizeof(table) / sizeof(table[0]) << std::endl;

#undef TABLE_SIZE_TEST

			std::cout << std::endl;
		}


		//=========================================================================================
		// [테스트 예제 3] defined 사용
		//=========================================================================================
		{
			std::cout << "==================================================" << std::endl;
			std::cout << "[테스트 3] defined 사용" << std::endl;
			std::cout << "==================================================" << std::endl;

#define ARRAY_SIZE_EXAMPLE 64

#if defined(ARRAY_SIZE_EXAMPLE)
#define FINAL_TABLE_SIZE ARRAY_SIZE_EXAMPLE
#elif !defined(BUFFER_SIZE_EXAMPLE)
#define FINAL_TABLE_SIZE 128
#else
#define FINAL_TABLE_SIZE BUFFER_SIZE_EXAMPLE
#endif

			int table[FINAL_TABLE_SIZE];
			std::cout << "FINAL_TABLE_SIZE = "
				<< sizeof(table) / sizeof(table[0]) << std::endl;

#undef ARRAY_SIZE_EXAMPLE
#undef FINAL_TABLE_SIZE

			std::cout << std::endl;
		}

		system("pause");
	}

